// Rules hash (D-75, D-84): a SHA-256 of every engine source file and of the shared screen flow
// (src/shared/flow.ts, which the room server uses to hold decisions and Ready marks across deploys), so a
// saved game, an exported log or a room can tell whether it runs under the same rules. Line endings are
// normalized, so Windows and Linux checkouts give the same hash. Any edit to these files changes it,
// comments included (deliberately conservative: a replay is only promised on identical code).
// Usage: node scripts/rules-version.mjs          write src/engine/rules-hash.ts
//        node scripts/rules-version.mjs --check  fail if src/engine/rules-hash.ts is out of date
//        node scripts/rules-version.mjs --list   print the hashed files
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const engineDir = join(root, 'src', 'engine');
const outFile = join(engineDir, 'rules-hash.ts');
/** Files outside src/engine that also decide how a logged game or a room plays (D-84). */
const EXTRA = [join(root, 'src', 'shared', 'flow.ts')];

function files(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((d) => (d.isDirectory() ? files(join(dir, d.name)) : [join(dir, d.name)]));
}

/** Every hashed file, relative to src/engine, sorted. */
export function hashedFiles() {
  return [...files(engineDir).filter((f) => f.endsWith('.ts') && f !== outFile), ...EXTRA]
    .map((f) => relative(engineDir, f).split('\\').join('/'))
    .sort();
}

/** The hash of the hashed sources as they are on disk now. */
export function computeRulesHash() {
  const h = createHash('sha256');
  for (const rel of hashedFiles()) {
    h.update(`${rel}\n`);
    h.update(readFileSync(join(engineDir, rel), 'utf8').replace(/\r\n/g, '\n'));
    h.update('\n\0\n');
  }
  return h.digest('hex').slice(0, 16);
}

/** The hash recorded in src/engine/rules-hash.ts. */
export function recordedRulesHash() {
  return /RULES_HASH = '([0-9a-f]+)'/.exec(readFileSync(outFile, 'utf8'))?.[1] ?? null;
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const now = computeRulesHash();
  if (process.argv.includes('--list')) {
    for (const rel of hashedFiles()) console.log(rel);
  } else if (process.argv.includes('--check')) {
    if (recordedRulesHash() !== now) {
      console.error(`src/engine/rules-hash.ts is out of date (engine sources hash to ${now}). Run: npm run rules-version`);
      process.exit(1);
    }
    console.log(`rules hash ${now} is current`);
  } else {
    writeFileSync(
      outFile,
      `// Generated by scripts/rules-version.mjs (D-75, D-84). Do not edit: run \`npm run rules-version\` after changing the engine or src/shared/flow.ts.\nexport const RULES_HASH = '${now}';\n`,
    );
    console.log(`wrote rules hash ${now}`);
  }
}
