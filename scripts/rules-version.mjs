// Rules hash (D-75): a SHA-256 of every engine source file, so a saved game or an exported log can tell
// whether it was played under the same rules. Line endings are normalized, so Windows and Linux
// checkouts give the same hash. Any edit under src/engine changes it, comments included (deliberately
// conservative: a replay is only promised on identical engine code).
// Usage: node scripts/rules-version.mjs          write src/engine/rules-hash.ts
//        node scripts/rules-version.mjs --check  fail if src/engine/rules-hash.ts is out of date
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const engineDir = join(root, 'src', 'engine');
const outFile = join(engineDir, 'rules-hash.ts');

function files(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((d) => (d.isDirectory() ? files(join(dir, d.name)) : [join(dir, d.name)]));
}

/** The hash of the engine sources as they are on disk now. */
export function computeRulesHash() {
  const h = createHash('sha256');
  const list = files(engineDir)
    .filter((f) => f.endsWith('.ts') && f !== outFile)
    .map((f) => relative(engineDir, f).split('\\').join('/'))
    .sort();
  for (const rel of list) {
    h.update(`${rel}\n`);
    h.update(readFileSync(join(engineDir, rel), 'utf8').replace(/\r\n/g, '\n'));
    h.update('\n\0\n');
  }
  return h.digest('hex').slice(0, 16);
}

/** The hash recorded in src/engine/rules-hash.ts. */
export function recordedRulesHash() {
  return /RULES_HASH = '([0-9a-f]+)'/.exec(readFileSync(outFile, 'utf8'))?.[1] ?? null;
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const now = computeRulesHash();
  if (process.argv.includes('--check')) {
    if (recordedRulesHash() !== now) {
      console.error(`src/engine/rules-hash.ts is out of date (engine sources hash to ${now}). Run: npm run rules-version`);
      process.exit(1);
    }
    console.log(`rules hash ${now} is current`);
  } else {
    writeFileSync(
      outFile,
      `// Generated by scripts/rules-version.mjs (D-75). Do not edit: run \`npm run rules-version\` after changing the engine.\nexport const RULES_HASH = '${now}';\n`,
    );
    console.log(`wrote rules hash ${now}`);
  }
}
